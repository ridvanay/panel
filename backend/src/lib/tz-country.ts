let zoneToCountry: Map<string, string> | null = null;

/** IANA dilimi → ISO 3166-1 alpha-2 ülke kodu (bilinmiyorsa `null`; `UTC`/`Etc/*` ülkesizdir). */
export function countryForTimeZone(timeZone: string | null | undefined): string | null {
  if (!timeZone) return null;
  if (!zoneToCountry) {
    zoneToCountry = new Map();
    for (const [cc, zones] of Object.entries(COUNTRY_ZONES)) for (const tz of zones.split("|")) zoneToCountry.set(tz, cc);
  }
  return zoneToCountry.get(timeZone) ?? null;
}

/** Ülkenin `zone.tab`'daki ilk (ana) dilimi. */
export function primaryZoneForCountry(countryCode: string | null | undefined): string | null {
  if (!countryCode) return null;
  const zones = COUNTRY_ZONES[countryCode.toUpperCase()];
  return zones ? zones.split("|")[0]! : null;
}
